#!/usr/bin/env python3
"""Build src/menu_text.asm from control/credits/readthis/ending txt files.

credits.txt / readthis.txt / ending.txt are split into screens on lines that are only '^'.
"""
from __future__ import annotations

import re
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "menu_text.asm"
CREDITS = ROOT / "credits.txt"
READTHIS = ROOT / "readthis.txt"
ENDING = ROOT / "ending.txt"

# label, source txt (no yellow title — body only)
SCREENS = (
	("control_text", ROOT / "control.txt"),
	("order_text", ROOT / "order.txt"),
)

_MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")
_DATE_IN_CREDITS = re.compile(
	r"\d{1,2} (?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) \d{4}"
)


def stamp_credits_date() -> None:
	"""Replace the build date in credits.txt with today (e.g. 12 Oct 2026)."""
	raw = CREDITS.read_text(encoding="utf-8", newline="")
	today = date.today()
	stamp = f"{today.day} {_MONTHS[today.month - 1]} {today.year}"
	updated, n = _DATE_IN_CREDITS.subn(stamp, raw, count=1)
	if n != 1:
		raise SystemExit(f"no build date in {CREDITS.name}")
	if updated != raw:
		CREDITS.write_text(updated, encoding="utf-8", newline="")


def esc_scr(s: str) -> str:
	"""Escape for ACME !scr \"...\"."""
	return s.replace("\\", "\\\\").replace('"', '\\"')


def emit_blob_lines(label: str, lines: list[str]) -> list[str]:
	while lines and not lines[-1].strip():
		lines = lines[:-1]
	out = [f"{label}"]
	for line in lines:
		body = line if line.strip() else " "
		out.append(f'\t!scr "{esc_scr(body)}",0')
	out.append("\t!byte 0")
	out.append("")
	return out


def emit_blob(label: str, path: Path) -> list[str]:
	return emit_blob_lines(label, path.read_text(encoding="utf-8").splitlines())


def split_caret_pages(text: str) -> list[list[str]]:
	pages: list[list[str]] = []
	cur: list[str] = []
	for line in text.splitlines():
		if line.strip() == "^":
			pages.append(cur)
			cur = []
		else:
			cur.append(line)
	pages.append(cur)
	cleaned: list[list[str]] = []
	for p in pages:
		while p and not p[0].strip():
			p = p[1:]
		while p and not p[-1].strip():
			p = p[:-1]
		if p:
			cleaned.append(p)
	return cleaned


def emit_caret_pages(path: Path, prefix: str, count_sym: str, lo_sym: str, hi_sym: str) -> list[str]:
	if not path.is_file():
		raise SystemExit(f"missing {path}")
	pages = split_caret_pages(path.read_text(encoding="utf-8"))
	if not pages:
		raise SystemExit(f"{path.name} has no screens")
	if len(pages) > 255:
		raise SystemExit(f"{path.name} has {len(pages)} screens; max 255")
	out: list[str] = [f"{count_sym} = {len(pages)}", ""]
	labels = [f"{prefix}{i}_text" for i in range(1, len(pages) + 1)]
	for label, lines in zip(labels, pages):
		out.extend(emit_blob_lines(label, lines))
	out.append(lo_sym)
	out.append("\t!byte " + ", ".join(f"<{n}" for n in labels))
	out.append(hi_sym)
	out.append("\t!byte " + ", ".join(f">{n}" for n in labels))
	out.append("")
	return out


def main() -> None:
	stamp_credits_date()
	out: list[str] = [
		"; Auto-generated by tools/gen_menu_text.py - edit *.txt in repo root",
		"; credits.txt / readthis.txt / ending.txt pages split on lines that are only '^'",
		"",
	]
	for label, path in SCREENS:
		if not path.is_file():
			raise SystemExit(f"missing {path}")
		out.extend(emit_blob(label, path))
	out.extend(emit_caret_pages(CREDITS, "credits", "CREDITS_PAGES", "credits_lo", "credits_hi"))
	out.extend(emit_caret_pages(READTHIS, "readthis", "READTHIS_PAGES", "readthis_lo", "readthis_hi"))
	out.extend(emit_caret_pages(ENDING, "ending", "ENDING_PAGES", "ending_lo", "ending_hi"))
	OUT.write_text("\n".join(out), encoding="utf-8")
	print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
	main()
