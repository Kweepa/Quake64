def main() -> None:
    ap = argparse.ArgumentParser(description="Generate streamed-AI GAME symbol include")
    ap.add_argument("--labels", default="game-ai.lbl")
    ap.add_argument(
        "--verify-labels",
        default=None,
        help="also require every exported address to match this label file",
    )
    args = ap.parse_args()
    path = Path(args.labels)
    if not path.is_file():
        path = ROOT / path
    labels = parse_labels(path)
    missing = [name for name in REQUIRED if name not in labels]
    if missing:
        raise SystemExit(f"{path}: missing AI symbols: {', '.join(missing)}")
    if args.verify_labels:
        verify_path = Path(args.verify_labels)
        if not verify_path.is_file():
            verify_path = ROOT / verify_path
        verify = parse_labels(verify_path)
        mismatch = [
            name
            for name in REQUIRED
            if name not in verify or verify[name] != labels[name]
        ]
        if mismatch:
            details = ", ".join(
                f"{name} ${labels[name]:04x}->"
                + (f"${verify[name]:04x}" if name in verify else "missing")
                for name in mismatch
            )
            raise SystemExit(f"{verify_path}: streamed-AI GAME symbol drift: {details}")
        print(f"Verified AI symbols against {verify_path}")
    lines = ["; Generated by tools/genaisymbols.py — fixed GAME entry addresses"]
    lines.extend(f"{name}\t= ${labels[name]:04x}" for name in REQUIRED)
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(REQUIRED)} symbols)")


if __name__ == "__main__":
    main()
