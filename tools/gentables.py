#!/usr/bin/env python3
"""Log / antilog / sin / cos LUTs ($F800) and Judd quarter-square tables."""

from __future__ import annotations

import math
from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / "src"
OUT = SRC / "tables.asm"
SQOUT = SRC / "sqtab.asm"


def bchunk(data: list[int], w: int = 16) -> str:
    lines = []
    for i in range(0, len(data), w):
        chunk = data[i : i + w]
        lines.append("\t!byte " + ",".join(f"${b:02x}" for b in chunk))
    return "\n".join(lines) + "\n"


def main() -> None:
    logtab = [0]
    for i in range(1, 256):
        logtab.append(max(0, min(255, int(round(32.0 * math.log2(i))))))

    alog = []
    for i in range(512):
        alog.append(min(255, int(round(2 ** (i / 32.0)))))

    sintab = []
    for i in range(256):
        v = int(round(127.0 * math.sin(i * 2.0 * math.pi / 256.0)))
        v = max(-127, min(127, v))
        sintab.append(v & 255)

    costab = []
    for i in range(256):
        v = int(round(127.0 * math.cos(i * 2.0 * math.pi / 256.0)))
        v = max(-127, min(127, v))
        costab.append(v & 255)

    parts = [
        "; Auto-generated by tools/gentables.py — do not edit\n",
        "; Order: log 256, alog 512, sin 256, cos 256  (runtime $F800)\n",
        bchunk(logtab),
        bchunk(alog),
        bchunk(sintab),
        bchunk(costab),
    ]
    OUT.write_text("".join(parts), encoding="utf-8")
    nlut = len(logtab) + len(alog) + len(sintab) + len(costab)
    print(f"Wrote {OUT} ({nlut} bytes)")

    sq = [(i * i) // 4 for i in range(512)]
    sqlo = [v & 255 for v in sq]
    sqhi = [v >> 8 for v in sq]

    # Companion table for pointer-based fast multiply:
    # a*m = sq[a+m] - negsq[a+(255-m)] with negsq[i] = ((i-255)^2)/4.
    # Page-aligned so a multiplier set-up is just 4 zp pointer lo-byte stores.
    negsq = [((i - 255) * (i - 255)) // 4 for i in range(512)]
    negsqlo = [v & 255 for v in negsq]
    negsqhi = [v >> 8 for v in negsq]

    # Reciprocal for mesh project: inv = (FOCAL<<16) / d for the normalized
    # divisor d in [128,255] (.invz always leaves dlo there since z >= ZCLIP).
    # Must match FOCAL in mem.asm. Exact div24u8 replacement.
    FOCAL = 100
    inv = [(FOCAL << 16) // d for d in range(128, 256)]
    invzl = [v & 255 for v in inv]
    invzh = [(v >> 8) & 255 for v in inv]

    SQOUT.write_text(
        "; Auto-generated by tools/gentables.py — Judd quarter-square (i*i)/4\n"
        "; Page-aligned: umul8a/b pointer sets store lo bytes only\n"
        "\t!align 255, 0\n"
        "sqlo\n"
        + bchunk(sqlo)
        + "sqhi\n"
        + bchunk(sqhi)
        + "; ((i-255)^2)/4 for the pointer multiply\n"
        + "negsqlo\n"
        + bchunk(negsqlo)
        + "negsqhi\n"
        + bchunk(negsqhi)
        + "; (FOCAL<<16)/d, d=128..255 — index (d & $7f)\n"
        + "invzl\n"
        + bchunk(invzl)
        + "invzh\n"
        + bchunk(invzh),
        encoding="utf-8",
    )
    print(f"Wrote {SQOUT} (2304 bytes + alignment)")


if __name__ == "__main__":
    main()
